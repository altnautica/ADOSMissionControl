#!/usr/bin/env node
/**
 * Pin the demo's first-party extension mirrors to their newest published
 * releases. For each extension below it takes the newest non-draft,
 * non-prerelease `<tag prefix><semver>` release of altnautica/ADOSExtensions
 * that carries a `.signed.adosplug` asset and writes
 * `src/mock/extension-manifests/<file>.generated.ts`: the manifest at that tag
 * verbatim, with the asset's URL, SHA-256 digest and size.
 *
 *   node scripts/sync-demo-extensions.mjs           rewrite the mirrors
 *   node scripts/sync-demo-extensions.mjs --check   exit 1 when one lags
 *
 * Release data comes from `gh api` (authenticated through `gh auth` or
 * `GH_TOKEN`).
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "altnautica/ADOSExtensions";
const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "mock", "extension-manifests");

/** file, exported constant, display name, extension directory, tag prefix. */
const EXTENSIONS = [
  ["capture", "CAPTURE", "Capture", "capture", "capture-v"],
  ["follow-me", "FOLLOW_ME", "Follow-Me", "follow-me", "follow-me-v"],
  ["gimbal", "GIMBAL", "MAVLink gimbal v2", "mavlink-gimbal-v2", "mavlink-gimbal-v2-v"],
  ["navigation", "NAVIGATION", "Navigation", "navigation", "navigation-v"],
  ["reconstruct", "RECONSTRUCT", "Reconstruct", "reconstruct", "reconstruct-v"],
  ["siyi-pod", "SIYI_POD", "SIYI pod", "siyi-pod", "siyi-pod-v"],
  ["thermal", "THERMAL", "FLIR Lepton thermal camera", "thermal-camera-flir-lepton-usb", "thermal-camera-flir-lepton-usb-v"],
];

const SEMVER = /^(\d+)\.(\d+)\.(\d+)$/;

function gh(path) {
  return JSON.parse(execFileSync("gh", ["api", "--paginate", "--slurp", path], { encoding: "utf8", maxBuffer: 64 << 20 }));
}

function newer(a, b) {
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] > b[i];
  return false;
}

function newestRelease(releases, prefix) {
  let best = null;
  for (const r of releases) {
    if (r.draft || r.prerelease || !r.tag_name.startsWith(prefix)) continue;
    const m = SEMVER.exec(r.tag_name.slice(prefix.length));
    if (!m) continue;
    const asset = r.assets.find((a) => a.name.endsWith(".signed.adosplug"));
    if (!asset || !asset.digest?.startsWith("sha256:")) continue;
    const version = m.slice(1).map(Number);
    if (!best || newer(version, best.version)) best = { tag: r.tag_name, version, asset };
  }
  if (!best) throw new Error(`no published ${prefix}<semver> release with a signed archive`);
  return best;
}

function manifestAt(dir, tag) {
  const file = gh(`repos/${REPO}/contents/extensions/${dir}/manifest.yaml?ref=${tag}`)[0];
  return Buffer.from(file.content, "base64").toString("utf8");
}

function render([file, constant, name], tag, asset, yaml) {
  const body = yaml.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return `// Generated by scripts/sync-demo-extensions.mjs; do not edit.
/**
 * @module mock/extension-manifests/${file}.generated
 * @description The published ${name} release the demo mirrors.
 * @license GPL-3.0-only
 */

import type { DemoExtensionRelease } from "./types";

export const ${constant}: DemoExtensionRelease = {
  tag: "${tag}",
  downloadUrl:
    "${asset.browser_download_url}",
  archiveSha256: "${asset.digest.slice("sha256:".length)}",
  archiveSizeBytes: ${asset.size},
  manifestYaml: \`${body}\`,
};
`;
}

const check = process.argv.includes("--check");
const releases = gh(`repos/${REPO}/releases?per_page=100`).flat();
let stale = 0;
for (const ext of EXTENSIONS) {
  const { tag, asset } = newestRelease(releases, ext[4]);
  const text = render(ext, tag, asset, manifestAt(ext[3], tag));
  const path = join(OUT_DIR, `${ext[0]}.generated.ts`);
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    current = null;
  }
  if (current === text) continue;
  stale++;
  if (check) console.error(`${ext[0]}.generated.ts lags ${tag}`);
  else {
    writeFileSync(path, text);
    console.log(`${ext[0]}.generated.ts: ${tag}`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("demo extension mirrors are current");
}
